use crate::model::SchemaField;
use crate::wire::{
    FIELD_OPTIONAL, FIELD_PRIVATE, FIELD_STATIC, FIELD_TRANSIENT, FIELD_UNRELIABLE, WireKind,
    array_assemblyscript_type, array_typescript_type,
};

pub(super) const HEADER: &str = "// <auto-generated />";

pub(super) fn capitalize(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
        None => String::new(),
    }
}

fn assemblyscript_string_literal(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            control if control.is_control() => {
                out.push_str(&format!("\\u{{{:x}}}", control as u32));
            }
            other => out.push(other),
        }
    }
    out.push('"');
    out
}

pub(super) fn default_literal(kind: WireKind, literal: &str) -> String {
    match kind {
        WireKind::Bool => literal.to_string(),
        WireKind::String => assemblyscript_string_literal(literal),
        WireKind::F32 | WireKind::F64 => {
            if literal.contains('.') || literal.contains('e') || literal.contains('E') {
                literal.to_string()
            } else {
                format!("{literal}.0")
            }
        }
        _ => literal.to_string(),
    }
}

pub(super) fn emit_field_builder(out: &mut String, field: &SchemaField) {
    if field.kind == WireKind::Array {
        out.push_str(&format!(
            "    .array(\"{}\", {})\n",
            field.name,
            field.element.unwrap_or(WireKind::F64).code()
        ));
    } else {
        out.push_str(&format!(
            "    .{}(\"{}\")\n",
            field.kind.builder_method(),
            field.name
        ));
    }
    if field.encoding.is_packed() && !field.encoding_is_default() {
        out.push_str(&format!(
            "    .range({}, {}, {})\n",
            field.encoding.bits,
            field.encoding.min(),
            field.encoding.max()
        ));
    }
    if field.flags & FIELD_OPTIONAL != 0 {
        out.push_str("    .optional()\n");
    }
    if field.flags & FIELD_STATIC != 0 {
        out.push_str("    .staticField()\n");
    }
    if field.flags & FIELD_TRANSIENT != 0 {
        out.push_str("    .transient()\n");
    }
    if field.flags & FIELD_PRIVATE != 0 {
        out.push_str("    .ownerOnly()\n");
    }
    if field.flags & FIELD_UNRELIABLE != 0 {
        out.push_str("    .unreliable()\n");
    }
    if let Some(path) = &field.nested_path {
        out.push_str(&format!("    .nested(\"{path}\")\n"));
    }
}

pub(super) fn emit_accessors(out: &mut String, index_prefix: &str, field: &SchemaField) {
    let ty = match field.kind {
        WireKind::Array => array_assemblyscript_type(field.element.unwrap_or(WireKind::F64)),
        other => other.assemblyscript_type(),
    };
    let suffix = field.kind.value_suffix();
    out.push_str(&format!(
        "\n    get {name}(): {ty} {{\n        return this.get{suffix}({prefix}_{name});\n    }}\n",
        name = field.name,
        prefix = index_prefix
    ));
    out.push_str(&format!(
        "    set {name}(v: {ty}) {{\n        this.set{suffix}({prefix}_{name}, v);\n    }}\n",
        name = field.name,
        prefix = index_prefix
    ));
    if field.optional() {
        let cap = capitalize(&field.name);
        out.push_str(&format!(
            "\n    has{cap}(): bool {{\n        return this.hasField({prefix}_{name});\n    }}\n",
            name = field.name,
            prefix = index_prefix
        ));
        out.push_str(&format!(
            "    clear{cap}(): void {{\n        this.clearField({prefix}_{name});\n    }}\n",
            prefix = index_prefix,
            name = field.name
        ));
    }
}

pub(super) fn field_typescript_type(field: &SchemaField) -> String {
    let base = match field.kind {
        WireKind::Array => array_typescript_type(field.element.unwrap_or(WireKind::F64)),
        WireKind::String => "string",
        other => other.typescript_type(),
    };
    if field.optional() {
        format!("{base} | null")
    } else {
        base.to_string()
    }
}
