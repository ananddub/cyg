use super::entity::{as_field_size, as_type, as_writer, emit_as_entity};

pub fn emit_as(
    schemas: &[crate::SchemaDef],
    root: Option<&crate::RootState>,
    _source: &str,
) -> String {
    let mut out = String::with_capacity(4096);
    out.push_str("// GENERATED by `ox-game schema-codegen --lang as` — DO NOT EDIT.\n");
    out.push_str("// Mutate these fields in your Room; `state.commit()` emits only\n// what changed. Wire rows: [tag][len][id u64][fields].\n\n");

    let Some(root) = root else { return out };
    let schema_by_name: std::collections::HashMap<&str, &crate::SchemaDef> =
        schemas.iter().map(|s| (s.name.as_str(), s)).collect();

    let mut tags: Vec<(String, u8)> = Vec::new();
    let mut tag: u8 = 1;
    for c in &root.collections {
        tags.push((c.name.clone(), tag));
        tag += 1;
    }
    let mut emitted: std::collections::HashSet<&str> = std::collections::HashSet::new();
    for c in &root.collections {
        if emitted.insert(c.schema.as_str()) {
            if let Some(def) = schema_by_name.get(c.schema.as_str()) {
                emit_as_entity(
                    &mut out,
                    &c.schema,
                    &def.fields,
                    &format!("collection '{}'", c.name),
                );
            }
        }
    }

    out.push_str("import { DeltaWriter, SchemaStateBase } from \"../cyg-server\";\n\n");
    out.push_str(&format!(
        "export class {} extends SchemaStateBase {{\n",
        root.name
    ));
    for c in &root.collections {
        out.push_str(&format!(
            "    {}: Map<u64, {}> = new Map();\n",
            c.name, c.schema
        ));
    }

    if !root.scalars.is_empty() {
        for (ri, f) in root.scalars.iter().enumerate() {
            out.push_str(&format!(
                "    {}: {} = 0;\n    private _rs{}: {} = 0;\n",
                f.name,
                as_type(&f.kind),
                ri,
                as_type(&f.kind)
            ));
        }
    }
    out.push_str("    private _w: DeltaWriter = new DeltaWriter(8192);\n\n");
    out.push_str("    /** Emit every dirty row; returns the packed (ptr<<32)|len delta. */\n    commit(): i64 {\n");
    for (name, t) in &tags {
        out.push_str(&format!(
            "        const ids{t} = this.{name}.keys(); const vals{t} = this.{name}.values();\n        for (let i = 0; i < ids{t}.length; i++) {{\n            const e{t} = vals{t}[i];\n            if (e{t}.dirty()) {{ e{t}.emit(this._w, {t}, ids{t}[i]); e{t}.keep(); }}\n        }}\n"
        ));
    }
    if !root.scalars.is_empty() {
        let dirty_cond: Vec<String> = root
            .scalars
            .iter()
            .enumerate()
            .map(|(ri, f)| format!("this.{} !== this._rs{}", f.name, ri))
            .collect();
        out.push_str(&format!(
            "        if ({}) {{\n            const w = this._w;\n",
            dirty_cond.join(" || ")
        ));
        let mut fb = 0usize;
        for f in &root.scalars {
            fb += as_field_size(&f.kind);
        }
        out.push_str(&format!("            w.beginEntity(0x10, {fb}, 0);\n"));
        for f in &root.scalars {
            out.push_str(&format!(
                "            w.{}(this.{} as {});\n",
                as_writer(&f.kind),
                f.name,
                if f.kind == crate::WireKind::F64 {
                    "f64"
                } else {
                    as_type(&f.kind)
                }
            ));
        }
        for (ri, f) in root.scalars.iter().enumerate() {
            out.push_str(&format!("            this._rs{} = this.{};\n", ri, f.name));
        }
        out.push_str("        }\n");
    }
    out.push_str("        return this._w.seal();\n    }\n}\n");
    out
}
