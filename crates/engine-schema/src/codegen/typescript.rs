use std::fmt::Write as _;

use crate::codegen::common::{escape_string, kind_name, kind_size, root_hash};
use crate::{RootState, SchemaDef, SchemaField};

/// TypeScript-side primitive for a wire kind.
fn ts_type(kind: crate::WireKind) -> &'static str {
    match kind {
        crate::WireKind::Bool => "boolean",
        crate::WireKind::String => "string",
        crate::WireKind::Array => "readonly number[]",
        _ => "number",
    }
}

fn ts_field_type(field: &SchemaField) -> String {
    let base = match field.kind {
        crate::WireKind::Array => {
            let _ = field.element;
            "readonly number[]".to_string()
        }
        other => ts_type(other).to_string(),
    };
    if field.optional() {
        format!("{base} | null")
    } else {
        base
    }
}

/// Runtime schema table, mirroring the Lua emitter's field metadata so the
/// typed room can attach a schema without shipping a separate descriptor.
fn ts_field_table(fields: &[SchemaField], indent: &str) -> String {
    let mut out = String::new();
    for field in fields {
        let element = field
            .element
            .map(|kind| format!("\"{}\"", kind_name(kind)))
            .unwrap_or_else(|| "\"none\"".into());
        let _ = writeln!(
            out,
            "{indent}{{ name: \"{name}\", kind: \"{kind}\", code: {code}, flags: {flags}, element: {element}, size: {size} }},",
            name = escape_string(&field.name),
            kind = kind_name(field.kind),
            code = field.kind.code(),
            flags = field.flags,
            element = element,
            size = kind_size(field),
        );
    }
    out
}

pub(crate) fn emit_ts(
    schemas: &[SchemaDef],
    root: Option<&RootState>,
    source_name: &str,
) -> String {
    let mut out = String::new();
    out.push_str("// <auto-generated>\n");
    let _ = writeln!(
        out,
        "// CYG schema bindings generated from {source_name}. Do not edit."
    );
    out.push_str("// Regenerate: ox-game schema-codegen . --lang ts\n");
    out.push_str("// </auto-generated>\n");
    let _ = writeln!(
        out,
        "import type {{ Room, SchemaMap }} from \"cyg\";\n"
    );

    out.push_str("export interface CygSchemaFieldDef {\n    name: string;\n    kind: string;\n    code: number;\n    flags: number;\n    element: string;\n    size: number;\n}\n\n");
    out.push_str("export interface CygSchemaTableDef {\n    name: string;\n    version: number;\n    hash: number;\n    fields: readonly CygSchemaFieldDef[];\n}\n");

    for schema in schemas {
        out.push('\n');
        out.push_str(&format!(
            "/** One decoded `{}` row (wire version {}). */\n",
            schema.name, schema.version
        ));
        out.push_str(&format!("export interface {}State {{\n", schema.name));
        out.push_str("    id: number;\n");
        for field in &schema.fields {
            let _ = writeln!(
                out,
                "    {name}: {ty};",
                name = field.name,
                ty = ts_field_type(field)
            );
        }
        out.push_str("}\n\n");
        out.push_str(&format!(
            "/** Runtime schema table for `{}` — pass to `useSchema()` / registry attach. */\n",
            schema.name
        ));
        out.push_str(&format!(
            "export const {}Schema: CygSchemaTableDef = {{\n    name: \"{}\",\n    version: {},\n    hash: {},\n    fields: [\n",
            schema.name,
            escape_string(&schema.name),
            schema.version,
            crate::wire_hash(schema)
        ));
        out.push_str(&ts_field_table(&schema.fields, "        "));
        out.push_str("    ],\n} as const;\n");
    }

    if let Some(root) = root {
        out.push('\n');
        out.push_str("/** Typed root state exposed as `room.state`. */\n");
        out.push_str(&format!(
            "export interface {}State {{\n",
            root.name
        ));
        for field in &root.scalars {
            let _ = writeln!(
                out,
                "    {name}: {ty};",
                name = field.name,
                ty = ts_field_type(field)
            );
        }
        for collection in &root.collections {
            let row = schemas
                .iter()
                .find(|schema| schema.name == collection.schema)
                .map(|schema| format!("{}State", schema.name))
                .unwrap_or_else(|| "SchemaEntity".to_string());
            let _ = writeln!(
                out,
                "    {name}: SchemaMap<{row}>;",
                name = collection.name,
                row = row
            );
        }
        out.push_str("}\n\n");
        out.push_str("/** Convenience alias for a room carrying this schema. */\n");
        out.push_str(&format!(
            "export type {}Room = Room<{}State>;\n",
            root.name, root.name
        ));
        out.push_str(&format!(
            "export const {}SchemaTable: CygSchemaTableDef = {{\n    name: \"{}\",\n    version: {},\n    hash: {},\n    fields: [\n",
            root.name,
            escape_string(&root.name),
            root.version,
            root_hash(root)
        ));
        out.push_str(&ts_field_table(&root.scalars, "        "));
        out.push_str("    ],\n} as const;\n");
        out.push_str(&format!(
            "\nexport const rootCollections = [\n"
        ));
        for collection in &root.collections {
            let _ = writeln!(
                out,
                "    {{ name: \"{}\", schema: \"{}\" }},",
                escape_string(&collection.name),
                escape_string(&collection.schema)
            );
        }
        out.push_str("] as const;\n");
    }

    out.push_str("\n/** Every schema table keyed by name — hand to `CYG.useSchema()` at runtime. */\n");
    out.push_str("export const schemas = {\n");
    for schema in schemas {
        let _ = writeln!(out, "    {0}: {0}Schema,", schema.name);
    }
    if let Some(root) = root {
        let _ = writeln!(out, "    {0}: {0}SchemaTable,", root.name);
    }
    out.push_str("} as const;\n");

    out.push_str("\ndeclare global {\n    interface Window {\n        CYGSchema: typeof schemas;\n    }\n}\n");

    out
}
