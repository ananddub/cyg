use engine_schema::{
    codegen::{emit, Language},
    ts,
};

const SCHEMA_TS: &str = r#"
import { schema, t } from "@colyseus/schema";

export const Player = schema({
    x: t.number(),
    y: t.number(),
    flags: t.uint32(),
}, "Player");

export const Projectile = schema({
    x: t.number(),
    active: t.boolean(),
}, "Projectile");

export const State = schema({
    players: t.map(Player),
    projectiles: t.array(t.ref("Projectile")),
    round: t.uint16(),
}, "State");
"#;

fn parsed() -> (Vec<engine_schema::SchemaDef>, Option<engine_schema::RootState>) {
    let p = ts::parse(SCHEMA_TS).expect("schema should parse");
    (p.schemas, p.root)
}

#[test]
fn typescript_codegen_emits_typed_state_and_schema_tables() {
    let (schemas, root) = parsed();
    let out = emit(Language::TypeScript, &schemas, root.as_ref(), "game.ts");

    // Header / source provenance
    assert!(out.contains("// <auto-generated>"));
    assert!(out.contains("// CYG schema bindings generated from game.ts. Do not edit."));
    assert!(out.contains("// </auto-generated>"));

    // Typed entity interfaces
    assert!(out.contains("export interface PlayerState {"));
    assert!(out.contains("    x: number;"));
    assert!(out.contains("    y: number;"));
    assert!(out.contains("    flags: number;"));
    assert!(out.contains("export interface ProjectileState {"));
    assert!(out.contains("    active: boolean;"));
    assert!(out.contains("export interface StateState {"));
    assert!(out.contains("    round: number;"));

    // Schema table descriptors
    assert!(out.contains("export const PlayerSchema: CygSchemaTableDef = {"));
    assert!(out.contains("    name: \"Player\","));
    assert!(out.contains("export const ProjectileSchema: CygSchemaTableDef = {"));
    assert!(out.contains("export const StateSchemaTable: CygSchemaTableDef = {"));
    assert!(out.contains("    name: \"State\","));

    // Field metadata includes kind/code/flags/size
    assert!(out.contains("kind: \"f64\""));
    assert!(out.contains("kind: \"u32\""));
    assert!(out.contains("kind: \"u16\""));
    assert!(out.contains("kind: \"bool\""));
    assert!(out.contains("code:"));

    // Registry + global declaration
    assert!(out.contains("export const schemas = {"));
    assert!(out.contains("    Player: PlayerSchema,"));
    assert!(out.contains("    Projectile: ProjectileSchema,"));
    assert!(out.contains("    State: StateSchemaTable,"));
    assert!(out.contains("interface Window {"));
    assert!(out.contains("CYGSchema: typeof schemas;"));
}

#[test]
fn typescript_codegen_is_deterministic() {
    let (schemas, root) = parsed();
    let a = emit(Language::TypeScript, &schemas, root.as_ref(), "game.ts");
    let b = emit(Language::TypeScript, &schemas, root.as_ref(), "game.ts");
    assert_eq!(a, b);
}
