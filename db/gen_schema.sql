-- Dump every public table as a standalone CREATE TABLE, one file per table.
-- The type spellings are canonicalised because FlashORM's Rust generator maps
-- `TIMESTAMPTZ` to `DateTime<Utc>`, while pg_dump's verbose
-- `timestamp with time zone` falls through to `NaiveDateTime`, which sqlx
-- cannot decode from a `timestamptz` column.
WITH raw AS (
  SELECT c.relname AS relname,
    'CREATE TABLE ' || c.relname || ' (' || chr(10) || '    ' || cols.body || ',' || chr(10) ||
    '    ' || cons.body || chr(10) || ');' || chr(10) || coalesce(idx.body, '') AS body
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  CROSS JOIN LATERAL (
    SELECT string_agg(
      '    ' || a.attname || ' ' ||
      CASE WHEN a.attidentity = 'a' THEN 'BIGINT GENERATED ALWAYS AS IDENTITY'
           WHEN a.attidentity = 'd' THEN format_type(a.atttypid, a.atttypmod) || ' GENERATED BY DEFAULT AS IDENTITY'
           ELSE format_type(a.atttypid, a.atttypmod) ||
                CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END ||
                COALESCE(' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid), '')
      END, ',' || chr(10) || '  ' ORDER BY a.attnum) AS body
    FROM pg_attribute a
    LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
  ) cols
  CROSS JOIN LATERAL (
    SELECT coalesce(string_agg(
      '    CONSTRAINT ' || con.conname || ' ' || pg_get_constraintdef(con.oid),
      ',' || chr(10) || '  '), '') AS body
    FROM pg_constraint con WHERE con.conrelid = c.oid
  ) cons
  LEFT JOIN LATERAL (
    SELECT chr(10) || string_agg(
      replace(pg_get_indexdef(x.indexrelid), 'public.', '') || ';',
      chr(10)
    ) || chr(10) AS body
    FROM pg_index x WHERE x.indrelid = c.oid AND NOT x.indisprimary
  ) idx ON TRUE
  WHERE n.nspname = 'public' AND c.relkind = 'r'
)
SELECT relname || chr(31) ||
  replace(replace(replace(body,
    'timestamp with time zone', 'TIMESTAMPTZ'),
    'character varying', 'VARCHAR'),
    '::VARCHAR', '::varchar') || chr(30)
FROM raw
ORDER BY relname;
