//-----------------------------------------------------------------------------
// CYGPhysicsWorld.cs
// Deterministic fixed-step 3D rigid body world: body management, integration,
// sleeping, CCD and checksums. Broadphase, solver and queries live in partial
// companion files.
// Zero UnityEngine dependencies. All simulation math is Q32.32 fixed-point.
//-----------------------------------------------------------------------------

using System;
using System.Collections.Generic;

namespace CookYourGame.Sim
{
    /// <summary>
    /// Deterministic 3D rigid body world with a fixed-iteration sequential
    /// impulse solver.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Boxes and capsules use their body rotation for narrowphase, queries and
    /// contacts. Dynamic bodies integrate gravity with semi-implicit Euler,
    /// linear/angular damping, sleeping and optional sphere CCD. Contacts and
    /// friction use a rotational impulse solver with a diagonal local inertia
    /// tensor, solved in deterministic pair order (ordered by body id) with fixed
    /// velocity and position iterations.
    /// </para>
    /// <para>
    /// Documented limitations: there is no convex-hull primitive and the joint
    /// set is limited to distance/spring constraints (no hinge or 6-DOF limits);
    /// CCD only sweeps dynamic spheres against static colliders, so box/capsule
    /// rotational tunneling is not handled; moving CCD targets are not supported.
    /// </para>
    /// </remarks>
    public sealed partial class CYGPhysicsWorld : ICollisionWorld
    {
        private static readonly FP TinyEpsilon = FP.FromFraction(1, 1000000);

        private readonly List<CYGPhysicsBody> _bodies = new List<CYGPhysicsBody>();
        private readonly List<CYGJoint> _joints = new List<CYGJoint>();
        private readonly List<CYGPhysicsEvent> _events = new List<CYGPhysicsEvent>(64);

        private int _activeBodyCount;

        // Reused per-step buffers. They grow only when the body/pair count grows.
        private FPAABB[] _aabbs = new FPAABB[0];
        private int[] _order = new int[0];
        private long[] _pairs = new long[0];
        private CYGManifold[] _manifolds = new CYGManifold[0];
        private long[] _contactKeys = new long[0];
        private long[] _triggerKeys = new long[0];
        private long[] _prevContactKeys = new long[0];
        private long[] _prevTriggerKeys = new long[0];

        private int _orderCount;
        private int _pairCount;
        private int _manifoldCount;
        private int _contactKeyCount;
        private int _triggerKeyCount;
        private int _prevContactKeyCount;
        private int _prevTriggerKeyCount;

        public CYGPhysicsSettings Settings { get; private set; }

        /// <summary>Number of completed simulation steps.</summary>
        public int Tick { get; private set; }

        /// <summary>Number of body slots, including removed inactive bodies.</summary>
        public int BodySlotCount => _bodies.Count;

        /// <summary>Number of active bodies.</summary>
        public int ActiveBodyCount => _activeBodyCount;

        /// <summary>Number of joint slots, including removed inactive joints.</summary>
        public int JointCount => _joints.Count;

        /// <summary>
        /// Events generated by the most recent step. The list is cleared at the
        /// start of every Step call and is ordered deterministically.
        /// </summary>
        public IReadOnlyList<CYGPhysicsEvent> Events => _events;

        public CYGPhysicsWorld()
            : this(new CYGPhysicsSettings())
        {
        }

        public CYGPhysicsWorld(CYGPhysicsSettings settings)
        {
            Settings = settings ?? new CYGPhysicsSettings();
            _events.Clear();
        }

        #region Body and Joint Management

        /// <summary>
        /// Adds a body and assigns it the next stable id. Returns the new id.
        /// </summary>
        public int AddBody(CYGPhysicsBody body)
        {
            if (body == null)
                throw new ArgumentNullException(nameof(body));

            ValidateShape(body.Collider.Shape);
            if (body.Layer < 0 || body.Layer > 31)
                throw new ArgumentOutOfRangeException(nameof(body), "Body layer must be in [0, 31].");

            body.Id = _bodies.Count;
            body.IsActive = true;
            body.IsAwake = true;
            body.SleepTimer = FP.Zero;
            body.RecalculateInertia();
            _bodies.Add(body);
            _activeBodyCount++;
            EnsureBodyBuffers(_bodies.Count);
            return body.Id;
        }

        /// <summary>Returns the active body or null when the id is unknown/removed.</summary>
        public CYGPhysicsBody GetBody(int id)
        {
            if ((uint)id >= (uint)_bodies.Count)
                return null;
            CYGPhysicsBody body = _bodies[id];
            return body != null && body.IsActive ? body : null;
        }

        /// <summary>
        /// Marks a body inactive. Ids are never reused; joints touching the body are
        /// deactivated.
        /// </summary>
        public bool RemoveBody(int id)
        {
            CYGPhysicsBody body = GetBody(id);
            if (body == null)
                return false;

            body.IsActive = false;
            body.IsAwake = false;
            _activeBodyCount--;

            for (int i = 0; i < _joints.Count; i++)
            {
                CYGJoint joint = _joints[i];
                if (joint != null && (joint.BodyA == id || joint.BodyB == id))
                    joint.IsActive = false;
            }

            return true;
        }

        /// <summary>Teleports a body and wakes it.</summary>
        public void SetBodyPose(int id, FPVector3 position, FPQuaternion rotation)
        {
            CYGPhysicsBody body = GetBody(id);
            if (body == null)
                throw new ArgumentOutOfRangeException(nameof(id));
            body.Position = position;
            body.Rotation = rotation.Normalized;
            body.Wake();
        }

        /// <summary>Sets linear/angular velocity and wakes the body.</summary>
        public void SetBodyVelocity(int id, FPVector3 linearVelocity, FPVector3 angularVelocity)
        {
            CYGPhysicsBody body = GetBody(id);
            if (body == null)
                throw new ArgumentOutOfRangeException(nameof(id));
            body.LinearVelocity = linearVelocity;
            body.AngularVelocity = angularVelocity;
            body.Wake();
        }

        /// <summary>Wakes a body and resets its sleep timer.</summary>
        public void WakeBody(int id)
        {
            CYGPhysicsBody body = GetBody(id);
            if (body != null)
                body.Wake();
        }

        /// <summary>Adds a joint and returns its stable index.</summary>
        public int AddJoint(CYGJoint joint)
        {
            if (joint == null)
                throw new ArgumentNullException(nameof(joint));
            if (joint.BodyA == joint.BodyB)
                throw new ArgumentException("A joint requires two distinct bodies.", nameof(joint));
            if (GetBody(joint.BodyA) == null || GetBody(joint.BodyB) == null)
                throw new ArgumentException("Joint body ids must reference active bodies.", nameof(joint));
            if (joint.RestLength < FP.Zero)
                throw new ArgumentOutOfRangeException(nameof(joint), "Joint rest length cannot be negative.");

            joint.Id = _joints.Count;
            joint.IsActive = true;
            _joints.Add(joint);

            GetBody(joint.BodyA).Wake();
            GetBody(joint.BodyB).Wake();
            return joint.Id;
        }

        public CYGJoint GetJoint(int id)
        {
            if ((uint)id >= (uint)_joints.Count)
                return null;
            CYGJoint joint = _joints[id];
            return joint != null && joint.IsActive ? joint : null;
        }

        public bool RemoveJoint(int id)
        {
            CYGJoint joint = GetJoint(id);
            if (joint == null)
                return false;
            joint.IsActive = false;
            return true;
        }

        #endregion

        #region Step

        /// <summary>Steps using <see cref="CYGPhysicsSettings.FixedDeltaTime"/>.</summary>
        public void Step()
        {
            Step(Settings.FixedDeltaTime);
        }

        /// <summary>
        /// Advances the simulation by one fixed step. Callers should pass the same
        /// delta time every step; the simulation itself does not accumulate time.
        /// </summary>
        public void Step(FP deltaTime)
        {
            if (deltaTime <= FP.Zero)
                throw new ArgumentOutOfRangeException(nameof(deltaTime), "Step delta time must be positive.");

            Tick++;
            _events.Clear();

            WakeJointBodies();
            ApplySpringForces(deltaTime);
            IntegrateBodies(deltaTime);

            BuildBroadphase();
            BuildManifoldsAndTriggerPairs();

            WakeBodiesFromManifolds();
            EmitContactEnterStayEvents();
            EmitTriggerEnterStayEvents();

            PrepareContactSolver();
            SolveContactVelocity(deltaTime);
            SaveWarmManifolds();
            SolveDistanceJointVelocity(deltaTime);
            CorrectContactPositions();
            SolveDistanceJointPositions();

            UpdateSleeping(deltaTime);

            EmitContactExitEvents();
            EmitTriggerExitEvents();
            CommitPairHistory();
        }

        /// <summary>
        /// Clears accumulated contact impulses and pair history. The next step
        /// then behaves as the first step of a fresh world, which is required
        /// when the authoritative state is rebuilt from an external snapshot
        /// (for example the ECS bridge) and re-simulated.
        /// </summary>
        public void ResetTransientState()
        {
            _warmManifoldCount = 0;
            _prevContactKeyCount = 0;
            _prevTriggerKeyCount = 0;
            _events.Clear();
        }

        private void IntegrateBodies(FP deltaTime)
        {
            for (int id = 0; id < _bodies.Count; id++)
            {
                CYGPhysicsBody body = _bodies[id];
                if (body == null || !body.IsActive || body.Type == CYGBodyType.Static)
                    continue;

                if (body.Type == CYGBodyType.Kinematic)
                {
                    IntegrateKinematicBody(body, deltaTime);
                    continue;
                }

                if (!body.IsAwake)
                    continue;

                FPVector3 gravity = Settings.Gravity * body.GravityScale;
                body.LinearVelocity += gravity * deltaTime;
                ApplyDamping(body, deltaTime);

                FPVector3 displacement = body.LinearVelocity * deltaTime;
                FP distance = displacement.Magnitude;
                FPVector3 target = body.Position + displacement;

                if (Settings.EnableCcd && body.EnableCcd && distance > TinyEpsilon &&
                    body.Collider.Shape.Type == CYGShapeType.Sphere)
                {
                    target = ApplyCcd(body, displacement, distance);
                }

                body.Position = target;
                IntegrateRotation(body, deltaTime);
            }
        }

        private void IntegrateKinematicBody(CYGPhysicsBody body, FP deltaTime)
        {
            body.Position += body.LinearVelocity * deltaTime;
            IntegrateRotation(body, deltaTime);
        }

        private static void IntegrateRotation(CYGPhysicsBody body, FP deltaTime)
        {
            FP angularSpeed = body.AngularVelocity.Magnitude;
            if (angularSpeed <= TinyEpsilon)
                return;

            FPQuaternion delta = FPQuaternion.FromAxisAngle(body.AngularVelocity, angularSpeed * deltaTime);
            body.Rotation = (delta * body.Rotation).Normalized;
        }

        private static void ApplyDamping(CYGPhysicsBody body, FP deltaTime)
        {
            FP linearDamping = FP.Max(body.LinearDamping, FP.Zero);
            if (linearDamping > FP.Zero)
                body.LinearVelocity *= FP.One / (FP.One + linearDamping * deltaTime);

            FP angularDamping = FP.Max(body.AngularDamping, FP.Zero);
            if (angularDamping > FP.Zero)
                body.AngularVelocity *= FP.One / (FP.One + angularDamping * deltaTime);
        }

        /// <summary>
        /// Conservative advancement for a dynamic sphere against static colliders.
        /// Sweeps the current sphere center by the step displacement and clamps to
        /// the nearest hit. Only the first static hit is considered; rotational CCD
        /// and moving targets are not supported.
        /// </summary>
        private FPVector3 ApplyCcd(CYGPhysicsBody body, FPVector3 displacement, FP distance)
        {
            FP radius = body.Collider.Shape.Radius;
            FPVector3 direction = displacement / distance;
            FPVector3 startCenter = body.Collider.GetWorldCenter(body.Position, body.Rotation);
            FPSphere sphere = new FPSphere(startCenter, radius);

            FP bestDistance = distance;
            bool hitAnything = false;

            for (int id = 0; id < _bodies.Count; id++)
            {
                CYGPhysicsBody other = _bodies[id];
                if (other == null || !other.IsActive || other.Id == body.Id)
                    continue;
                if (other.Type != CYGBodyType.Static || other.Collider.IsTrigger)
                    continue;

                FPVector3 otherCenter = other.WorldCenter;
                CYGShapeType otherType = other.Collider.Shape.Type;
                FPRaycastHit hit;

                if (otherType == CYGShapeType.Box)
                {
                    if (FPRaycast.SphereCast(sphere, direction, distance, other.Collider.Shape.GetAABB(otherCenter), out hit))
                    {
                        if (hit.Distance < bestDistance)
                        {
                            bestDistance = hit.Distance;
                            hitAnything = true;
                        }
                    }
                }
                else if (otherType == CYGShapeType.Sphere)
                {
                    FPSphere target = new FPSphere(otherCenter, other.Collider.Shape.Radius);
                    if (FPRaycast.SphereCast(sphere, direction, distance, target, out hit))
                    {
                        if (hit.Distance < bestDistance)
                        {
                            bestDistance = hit.Distance;
                            hitAnything = true;
                        }
                    }
                }
                else if (otherType == CYGShapeType.Mesh)
                {
                    CYGStaticMesh mesh = CYGMeshRegistry.Get(other.Collider.Shape.MeshId);
                    if (mesh != null && mesh.SphereCast(sphere, direction, distance, out hit))
                    {
                        if (hit.Distance < bestDistance)
                        {
                            bestDistance = hit.Distance;
                            hitAnything = true;
                        }
                    }
                }
                else
                {
                    FPCapsule target = other.Collider.GetWorldCapsule(otherCenter);
                    if (FPRaycast.SphereCast(sphere, direction, distance, target, out hit))
                    {
                        if (hit.Distance < bestDistance)
                        {
                            bestDistance = hit.Distance;
                            hitAnything = true;
                        }
                    }
                }
            }

            if (!hitAnything)
                return body.Position + displacement;

            if (bestDistance < FP.Zero)
                bestDistance = FP.Zero;
            return body.Position + direction * bestDistance;
        }

        private void UpdateSleeping(FP deltaTime)
        {
            if (!Settings.EnableSleeping)
                return;

            FP linearThreshold = FP.Max(Settings.SleepLinearThreshold, FP.Zero);
            FP angularThreshold = FP.Max(Settings.SleepAngularThreshold, FP.Zero);
            FP linearSquared = linearThreshold * linearThreshold;
            FP angularSquared = angularThreshold * angularThreshold;

            for (int id = 0; id < _bodies.Count; id++)
            {
                CYGPhysicsBody body = _bodies[id];
                if (body == null || !body.IsActive || body.Type != CYGBodyType.Dynamic || !body.IsAwake)
                    continue;

                if (body.LinearVelocity.SqrMagnitude <= linearSquared &&
                    body.AngularVelocity.SqrMagnitude <= angularSquared)
                {
                    body.SleepTimer += deltaTime;
                    if (body.SleepTimer >= Settings.SleepDelay)
                        body.Sleep();
                }
                else
                {
                    body.SleepTimer = FP.Zero;
                }
            }
        }

        #endregion

        #region Determinism

        /// <summary>
        /// CRC32 over the deterministic body order (ascending id). The tick, active
        /// body count and each body's motion type, pose, velocities and awake state
        /// are hashed.
        /// </summary>
        public uint ComputeChecksum()
        {
            uint crc = CYGPhysicsHash.Seed;
            CYGChecksum.HashInt(ref crc, Tick);
            CYGChecksum.HashInt(ref crc, _activeBodyCount);

            for (int id = 0; id < _bodies.Count; id++)
            {
                CYGPhysicsBody body = _bodies[id];
                if (body == null || !body.IsActive)
                    continue;
                CYGPhysicsHash.HashBody(ref crc, body);
            }

            return CYGPhysicsHash.Finish(crc);
        }

        #endregion

        #region Buffers and Validation

        private static void ValidateShape(CYGShape shape)
        {
            if (shape.Type == CYGShapeType.Box)
            {
                if (shape.HalfExtents.x <= FP.Zero || shape.HalfExtents.y <= FP.Zero || shape.HalfExtents.z <= FP.Zero)
                    throw new ArgumentException("Box half extents must be positive.");
                return;
            }

            if (shape.Type == CYGShapeType.Mesh)
            {
                if (shape.MeshId == 0)
                    throw new ArgumentException("Mesh shape requires a non-zero mesh id.");
                if (shape.HalfExtents.x < FP.Zero || shape.HalfExtents.y < FP.Zero || shape.HalfExtents.z < FP.Zero)
                    throw new ArgumentException("Mesh bounds must not be negative.");
                return;
            }

            if (shape.Radius <= FP.Zero)
                throw new ArgumentException("Shape radius must be positive.");

            if (shape.Type == CYGShapeType.Capsule)
            {
                if (shape.Height < shape.Radius * FP.FromInt(2))
                    throw new ArgumentException("Capsule height must be at least twice its radius.");
            }
        }

        private void EnsureBodyBuffers(int bodyCount)
        {
            EnsureArraySize(ref _aabbs, bodyCount);
            EnsureArraySize(ref _order, bodyCount);
            EnsureArraySize(ref _pairs, Math.Max(16, bodyCount * 4));
            EnsureArraySize(ref _manifolds, Math.Max(16, bodyCount * 2));
            EnsureArraySize(ref _contactKeys, Math.Max(16, bodyCount * 2));
            EnsureArraySize(ref _triggerKeys, Math.Max(16, bodyCount));
            EnsureArraySize(ref _prevContactKeys, Math.Max(16, bodyCount * 2));
            EnsureArraySize(ref _prevTriggerKeys, Math.Max(16, bodyCount));
        }

        private static void EnsureArraySize<T>(ref T[] array, int required)
        {
            if (array.Length >= required)
                return;
            int capacity = array.Length == 0 ? Math.Max(16, required) : array.Length;
            while (capacity < required)
                capacity *= 2;
            array = new T[capacity];
        }

        #endregion
    }
}
