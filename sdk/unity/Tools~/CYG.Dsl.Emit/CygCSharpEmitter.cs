using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using CookYourGame.Dsl;

namespace CookYourGame.Dsl.Emit
{
    /// <summary>
    /// Emits plain C# declarations. Wire codecs are intentionally left to the
    /// Roslyn [CYGValue]/[CYGComponent] generator so .cyg files and hand-written
    /// components can never drift into two different serializers.
    /// </summary>
    public sealed class CygCSharpEmitter : ICygEmitter
    {
        public CygEmitResult Emit(CygModule module, CygEmitOptions options)
        {
            var result = new CygEmitResult();
            if (module == null)
            {
                result.Diagnostics.Add(new CygDiagnostic(
                    CygDiagnosticIds.Emit,
                    CygSeverity.Error,
                    "Cannot emit a null module.",
                    CygSpan.None));
                return result;
            }

            foreach (CygDiagnostic diagnostic in module.Diagnostics)
            {
                if (diagnostic.Severity == CygSeverity.Error)
                {
                    result.Diagnostics.Add(diagnostic);
                }
            }

            if (result.Diagnostics.Count > 0)
            {
                return result;
            }

            options = options ?? new CygEmitOptions();
            string? ns = string.IsNullOrWhiteSpace(options.Namespace) ? module.Namespace : options.Namespace;
            var emitter = new Emitter(module, ns ?? string.Empty, result.Diagnostics);
            string content = emitter.EmitModule();

            if (result.Diagnostics.Any(d => d.Severity == CygSeverity.Error))
            {
                return result;
            }

            string fileName = FileName(module);
            result.Files.Add(new CygEmittedFile(fileName, content));
            return result;
        }

        private static string FileName(CygModule module)
        {
            string path = module.SourcePath ?? string.Empty;
            string stem = string.IsNullOrEmpty(path)
                ? "CYGModule"
                : System.IO.Path.GetFileNameWithoutExtension(path);
            stem = CygNames.SanitizeIdentifier(stem);
            return stem + ".cyg.g.cs";
        }

        private sealed class Emitter
        {
            private const string Indent = "    ";

            private readonly CygModule _module;
            private readonly string _namespace;
            private readonly List<CygDiagnostic> _diagnostics;
            private readonly StringBuilder _sb = new StringBuilder(8192);

            public Emitter(CygModule module, string ns, List<CygDiagnostic> diagnostics)
            {
                _module = module;
                _namespace = ns ?? string.Empty;
                _diagnostics = diagnostics;
            }

            public string EmitModule()
            {
                _sb.AppendLine("// <auto-generated />");
                _sb.AppendLine("// Generated from " + (_module.SourcePath ?? "<memory>") + " by the CYG DSL compiler.");
                _sb.AppendLine("// Manual edits will be lost when the compiler runs again.");
                _sb.AppendLine("#pragma warning disable");
                _sb.AppendLine("using CookYourGame.Sim;");
                _sb.AppendLine();

                bool hasNamespace = !string.IsNullOrEmpty(_namespace);
                if (hasNamespace)
                {
                    _sb.Append("namespace ").Append(NamespaceName(_namespace)).AppendLine();
                    _sb.AppendLine("{");
                }

                string indent = hasNamespace ? Indent : string.Empty;
                EmitTypes(indent);

                if (hasNamespace)
                {
                    _sb.AppendLine("}");
                }

                return _sb.ToString();
            }

            private void EmitTypes(string indent)
            {
                foreach (CygEnumDecl enumDecl in _module.Enums)
                {
                    EmitEnum(indent, enumDecl);
                    _sb.AppendLine();
                }

                foreach (CygAssetDecl asset in _module.Assets)
                {
                    EmitAssetRef(indent, asset);
                    _sb.AppendLine();
                }

                foreach (CygStructDecl structDecl in _module.Structs)
                {
                    EmitStruct(indent, structDecl);
                    _sb.AppendLine();
                }

                foreach (CygComponentDecl component in _module.Components)
                {
                    EmitComponent(indent, component);
                    _sb.AppendLine();
                }

                foreach (CygUnionDecl union in _module.Unions)
                {
                    EmitUnion(indent, union);
                    _sb.AppendLine();
                }

                if (_module.Input != null)
                {
                    EmitInput(indent, _module.Input);
                    _sb.AppendLine();
                }

                if (_module.Global != null)
                {
                    EmitGlobal(indent, _module.Global);
                    _sb.AppendLine();
                }

                foreach (CygEventDecl eventDecl in _module.Events)
                {
                    EmitEvent(indent, eventDecl);
                    _sb.AppendLine();
                }

                foreach (CygCommandDecl command in _module.Commands)
                {
                    EmitCommand(indent, command);
                    _sb.AppendLine();
                }

                int signalIndex = 1;
                foreach (CygSignalDecl signal in _module.Signals)
                {
                    EmitSignal(indent, signal, signalIndex++);
                    _sb.AppendLine();
                }

                EmitSupportTypes(indent);
            }

            private void EmitEnum(string indent, CygEnumDecl declaration)
            {
                if (declaration.IsFlags)
                {
                    _sb.Append(indent).AppendLine("[System.Flags]");
                }

                _sb.Append(indent).Append("public enum ").Append(Identifier(declaration.Name))
                    .Append(" : ").Append(PrimitiveName(declaration.Underlying)).AppendLine();
                _sb.Append(indent).AppendLine("{");
                for (int i = 0; i < declaration.Members.Count; i++)
                {
                    CygEnumMember member = declaration.Members[i];
                    _sb.Append(indent).Append(Indent).Append(Identifier(member.Name))
                        .Append(" = ").Append((member.Value ?? i).ToString(CultureInfo.InvariantCulture));
                    if (i + 1 < declaration.Members.Count)
                    {
                        _sb.Append(',');
                    }
                    _sb.AppendLine();
                }

                _sb.Append(indent).AppendLine("}");
            }

            private void EmitAssetRef(string indent, CygAssetDecl asset)
            {
                string name = Identifier(asset.Name + "Ref");
                _sb.Append(indent).AppendLine("[CYGValue]");
                _sb.Append(indent).Append("public partial struct ").Append(name).AppendLine();
                _sb.Append(indent).AppendLine("{");
                string body = indent + Indent;
                _sb.Append(body).AppendLine("public int Id;");
                _sb.AppendLine();
                _sb.Append(body).Append("public ").Append(name).AppendLine("(int id)");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    Id = id;");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();
                _sb.Append(body).Append("public static readonly ").Append(name).Append(" None = new ")
                    .Append(name).AppendLine("(0);");
                _sb.AppendLine();
                _sb.Append(body).AppendLine("public bool IsNone");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    get { return Id == 0; }");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();
                _sb.Append(body).AppendLine("public override string ToString()");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).Append("    return IsNone ? \"").Append(name).Append("\" : \"").Append(name)
                    .Append("(\" + Id + \")\";").AppendLine();
                _sb.Append(body).AppendLine("}");
                _sb.Append(indent).AppendLine("}");
            }

            private void EmitStruct(string indent, CygStructDecl declaration)
            {
                _sb.Append(indent).AppendLine("[CYGValue]");
                _sb.Append(indent).Append("public partial struct ").Append(Identifier(declaration.Name)).AppendLine();
                _sb.Append(indent).AppendLine("{");
                EmitFields(indent + Indent, declaration.Fields);
                _sb.Append(indent).AppendLine("}");
            }

            private void EmitComponent(string indent, CygComponentDecl declaration)
            {
                if (!declaration.Id.HasValue)
                {
                    _diagnostics.Add(new CygDiagnostic(
                        CygDiagnosticIds.Emit,
                        CygSeverity.Error,
                        $"Component '{declaration.Name}' reached the emitter without an id.",
                        declaration.Span));
                    return;
                }

                _sb.Append(indent).Append("[CYGComponent(").Append(declaration.Id.Value).AppendLine(")]");
                _sb.Append(indent).Append("public partial struct ").Append(Identifier(declaration.Name)).AppendLine();
                _sb.Append(indent).AppendLine("{");
                EmitFields(indent + Indent, declaration.Fields);
                _sb.Append(indent).AppendLine("}");
            }

            private void EmitFields(string indent, IEnumerable<CygField> fields)
            {
                foreach (CygField field in fields)
                {
                    _sb.Append(indent).Append("public ").Append(TypeName(field.Type)).Append(' ')
                        .Append(Identifier(field.Name)).AppendLine(";");
                }
            }

            private void EmitUnion(string indent, CygUnionDecl union)
            {
                string unionName = Identifier(union.Name);
                var variantNames = new List<string>(union.Variants.Count);
                foreach (CygUnionVariant variant in union.Variants)
                {
                    variantNames.Add(Identifier(union.Name + variant.Name));
                }

                for (int i = 0; i < union.Variants.Count; i++)
                {
                    CygUnionVariant variant = union.Variants[i];
                    _sb.Append(indent).AppendLine("[CYGValue]");
                    _sb.Append(indent).Append("public partial struct ").Append(variantNames[i]).AppendLine();
                    _sb.Append(indent).AppendLine("{");
                    EmitFields(indent + Indent, variant.Fields);
                    _sb.Append(indent).AppendLine("}");
                    _sb.AppendLine();
                }

                int longest = 0;
                foreach (CygUnionVariant variant in union.Variants)
                {
                    int? size = CygLayout.SizeOfFields(_module, variant.Fields);
                    if (size == null)
                    {
                        _diagnostics.Add(new CygDiagnostic(
                            CygDiagnosticIds.Emit,
                            CygSeverity.Error,
                            $"Cannot compute the wire size of union variant '{union.Name}.{variant.Name}'.",
                            variant.Span));
                        return;
                    }

                    longest = Math.Max(longest, size.Value);
                }

                int unionSize = 1 + longest;
                string body = indent + Indent;

                _sb.Append(indent).Append("public partial struct ").Append(unionName).AppendLine(" : ICYGValue");
                _sb.Append(indent).AppendLine("{");
                _sb.Append(body).Append("public const int SizeInBytes = ").Append(unionSize).AppendLine(";");
                for (int i = 0; i < union.Variants.Count; i++)
                {
                    _sb.Append(body).Append("public const byte ").Append(Identifier("Tag" + union.Variants[i].Name))
                        .Append(" = ").Append(i + 1).AppendLine(";");
                }
                _sb.AppendLine();

                _sb.Append(body).AppendLine("public byte Tag;");
                for (int i = 0; i < union.Variants.Count; i++)
                {
                    _sb.Append(body).Append("public ").Append(variantNames[i]).Append(' ')
                        .Append(Identifier(union.Variants[i].Name)).AppendLine(";");
                }
                _sb.AppendLine();

                _sb.Append(body).AppendLine("public int WireSize");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    get { return SizeInBytes; }");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();

                _sb.Append(body).AppendLine("public readonly int WriteTo(byte[] buffer, int offset)");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    CYGWire.RequireWritable(buffer, offset, SizeInBytes);");
                _sb.Append(body).AppendLine("    CYGWire.WriteByte(buffer, offset, Tag);");
                _sb.Append(body).AppendLine("    int cursor = offset + 1;");
                _sb.Append(body).AppendLine("    switch (Tag)");
                _sb.Append(body).AppendLine("    {");
                for (int i = 0; i < union.Variants.Count; i++)
                {
                    string field = Identifier(union.Variants[i].Name);
                    _sb.Append(body).Append("        case ").Append(i + 1).AppendLine(":");
                    _sb.Append(body).Append("            ").Append(field).AppendLine(".WriteTo(buffer, cursor);");
                    _sb.Append(body).Append("            cursor += ").Append(variantNames[i]).AppendLine(".SizeInBytes;");
                    _sb.Append(body).AppendLine("            break;");
                }
                _sb.Append(body).AppendLine("        default:");
                _sb.Append(body).AppendLine("            break;");
                _sb.Append(body).AppendLine("    }");
                _sb.Append(body).AppendLine("    for (int i = cursor; i < offset + SizeInBytes; i++)");
                _sb.Append(body).AppendLine("    {");
                _sb.Append(body).AppendLine("        buffer[i] = 0;");
                _sb.Append(body).AppendLine("    }");
                _sb.Append(body).AppendLine("    return SizeInBytes;");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();

                _sb.Append(body).AppendLine("public void ReadFrom(byte[] buffer, int offset)");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    CYGWire.RequireReadable(buffer, offset, SizeInBytes);");
                _sb.Append(body).Append("    ").Append(unionName).AppendLine(" value = default(" + unionName + ");");
                _sb.Append(body).AppendLine("    value.Tag = CYGWire.ReadByte(buffer, offset);");
                _sb.Append(body).AppendLine("    int cursor = offset + 1;");
                _sb.Append(body).AppendLine("    switch (value.Tag)");
                _sb.Append(body).AppendLine("    {");
                for (int i = 0; i < union.Variants.Count; i++)
                {
                    string field = Identifier(union.Variants[i].Name);
                    _sb.Append(body).Append("        case ").Append(i + 1).AppendLine(":");
                    _sb.Append(body).Append("            value.").Append(field).AppendLine(".ReadFrom(buffer, cursor);");
                    _sb.Append(body).Append("            cursor += ").Append(variantNames[i]).AppendLine(".SizeInBytes;");
                    _sb.Append(body).AppendLine("            break;");
                }
                _sb.Append(body).AppendLine("        default:");
                _sb.Append(body).AppendLine("            value.Tag = 0;");
                _sb.Append(body).AppendLine("            break;");
                _sb.Append(body).AppendLine("    }");
                _sb.Append(body).AppendLine("    this = value;");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();

                _sb.Append(body).AppendLine("public readonly void ComputeChecksum(ref uint crc)");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    CYGChecksum.HashByte(ref crc, Tag);");
                _sb.Append(body).AppendLine("    switch (Tag)");
                _sb.Append(body).AppendLine("    {");
                for (int i = 0; i < union.Variants.Count; i++)
                {
                    _sb.Append(body).Append("        case ").Append(i + 1).AppendLine(":");
                    _sb.Append(body).Append("            ").Append(Identifier(union.Variants[i].Name))
                        .AppendLine(".ComputeChecksum(ref crc);");
                    _sb.Append(body).AppendLine("            break;");
                }
                _sb.Append(body).AppendLine("        default:");
                _sb.Append(body).AppendLine("            break;");
                _sb.Append(body).AppendLine("    }");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();

                _sb.Append(body).Append("public readonly void CopyTo(ref ").Append(unionName).AppendLine(" destination)");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    destination = this;");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();

                _sb.Append(body).AppendLine("public void Clear()");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).Append("    this = default(").Append(unionName).AppendLine(");");
                _sb.Append(body).AppendLine("}");

                _sb.Append(indent).AppendLine("}");
            }

            private void EmitInput(string indent, CygInputDecl input)
            {
                var buttons = input.Fields.Where(f => f.IsButton).ToList();
                var fields = input.Fields.Where(f => !f.IsButton).ToList();
                string storage = ButtonStorage(buttons.Count);
                string body = indent + Indent;

                _sb.Append(indent).AppendLine("[CYGValue]");
                _sb.Append(indent).AppendLine("public partial struct CYGInput");
                _sb.Append(indent).AppendLine("{");
                if (buttons.Count > 0)
                {
                    _sb.Append(body).Append("private ").Append(storage).AppendLine(" _buttons;");
                    for (int i = 0; i < buttons.Count; i++)
                    {
                        string property = Identifier(buttons[i].Name);
                        string mask = ButtonMask(storage, i);
                        _sb.Append(body).Append("public bool ").Append(property).AppendLine();
                        _sb.Append(body).AppendLine("{");
                        _sb.Append(body).Append("    get { return (_buttons & ").Append(mask).AppendLine(") != 0; }");
                        _sb.Append(body).AppendLine("    set");
                        _sb.Append(body).AppendLine("    {");
                        _sb.Append(body).AppendLine("        if (value)");
                        _sb.Append(body).AppendLine("        {");
                        _sb.Append(body).Append("            _buttons |= ").Append(mask).AppendLine(";");
                        _sb.Append(body).AppendLine("        }");
                        _sb.Append(body).AppendLine("        else");
                        _sb.Append(body).AppendLine("        {");
                        _sb.Append(body).Append("            _buttons = (").Append(storage).Append(")(_buttons & ~")
                            .Append(mask).AppendLine(");");
                        _sb.Append(body).AppendLine("        }");
                        _sb.Append(body).AppendLine("    }");
                        _sb.Append(body).AppendLine("}");
                    }
                }

                foreach (CygInputField field in fields)
                {
                    _sb.Append(body).Append("public ").Append(TypeName(field.Type!)).Append(' ')
                        .Append(Identifier(field.Name)).AppendLine(";");
                }

                _sb.Append(indent).AppendLine("}");
            }

            private void EmitGlobal(string indent, CygGlobalDecl global)
            {
                _sb.Append(indent).AppendLine("[CYGValue]");
                _sb.Append(indent).AppendLine("public partial struct CYGGlobals");
                _sb.Append(indent).AppendLine("{");
                EmitFields(indent + Indent, global.Fields);
                _sb.Append(indent).AppendLine("}");
            }

            private void EmitEvent(string indent, CygEventDecl eventDecl)
            {
                if (!eventDecl.Id.HasValue)
                {
                    _diagnostics.Add(new CygDiagnostic(
                        CygDiagnosticIds.Emit,
                        CygSeverity.Error,
                        $"Event '{eventDecl.Name}' reached the emitter without an id.",
                        eventDecl.Span));
                    return;
                }

                _sb.Append(indent).AppendLine("[CYGValue]");
                _sb.Append(indent).Append("public partial struct ").Append(Identifier(eventDecl.Name)).AppendLine();
                _sb.Append(indent).AppendLine("{");
                string body = indent + Indent;
                _sb.Append(body).Append("public const int EventId = ").Append(eventDecl.Id.Value).AppendLine(";");
                _sb.Append(body).Append("public const bool Synced = ").Append(eventDecl.Synced ? "true" : "false").AppendLine(";");
                EmitFields(body, eventDecl.Fields);
                _sb.Append(indent).AppendLine("}");
            }

            private void EmitCommand(string indent, CygCommandDecl command)
            {
                if (!command.Id.HasValue)
                {
                    _diagnostics.Add(new CygDiagnostic(
                        CygDiagnosticIds.Emit,
                        CygSeverity.Error,
                        $"Command '{command.Name}' reached the emitter without an id.",
                        command.Span));
                    return;
                }

                string payloadName = Identifier(command.Name);
                string adapterName = Identifier(command.Name + "Command");
                string body = indent + Indent;

                _sb.Append(indent).AppendLine("[CYGValue]");
                _sb.Append(indent).Append("public partial struct ").Append(payloadName).AppendLine();
                _sb.Append(indent).AppendLine("{");
                _sb.Append(body).Append("public const int CommandId = ").Append(command.Id.Value).AppendLine(";");
                EmitFields(body, command.Fields);
                _sb.Append(indent).AppendLine("}");
                _sb.AppendLine();

                _sb.Append(indent).Append("public partial class ").Append(adapterName).AppendLine(" : CYGCommand");
                _sb.Append(indent).AppendLine("{");
                _sb.Append(body).Append("public const int CommandTypeId = ").Append(payloadName).AppendLine(".CommandId;");
                _sb.Append(body).Append("public ").Append(payloadName).AppendLine(" Payload;");
                _sb.AppendLine();
                _sb.Append(body).AppendLine("public override int TypeId");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    get { return CommandTypeId; }");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();
                _sb.Append(body).AppendLine("public override int PayloadSize");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).Append("    get { return ").Append(payloadName).AppendLine(".SizeInBytes; }");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();
                _sb.Append(body).AppendLine("public override int WritePayload(byte[] buffer, int offset)");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    return Payload.WriteTo(buffer, offset);");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();
                _sb.Append(body).AppendLine("public override void ReadPayload(byte[] buffer, int offset, int length)");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).Append("    if (length != ").Append(payloadName).AppendLine(".SizeInBytes)");
                _sb.Append(body).AppendLine("    {");
                _sb.Append(body).Append("        throw new System.InvalidOperationException(\"").Append(payloadName)
                    .Append(" command payload must be \" + ").Append(payloadName)
                    .AppendLine(".SizeInBytes + \" bytes, got \" + length + \".\");");
                _sb.Append(body).AppendLine("    }");
                _sb.Append(body).AppendLine("    Payload.ReadFrom(buffer, offset);");
                _sb.Append(body).AppendLine("}");
                _sb.Append(indent).AppendLine("}");
            }

            private void EmitSignal(string indent, CygSignalDecl signal, int index)
            {
                _sb.Append(indent).AppendLine("[CYGValue]");
                _sb.Append(indent).Append("public partial struct ").Append(Identifier(signal.Name)).AppendLine();
                _sb.Append(indent).AppendLine("{");
                string body = indent + Indent;
                _sb.Append(body).Append("public const int SignalIndex = ").Append(index).AppendLine(";");
                foreach (CygSignalParam parameter in signal.Parameters)
                {
                    _sb.Append(body).Append("public ").Append(TypeName(parameter.Type)).Append(' ')
                        .Append(Identifier(parameter.Name)).AppendLine(";");
                }
                _sb.Append(indent).AppendLine("}");
            }

            private void EmitSupportTypes(string indent)
            {
                var support = new Dictionary<string, CygTypeRef>(StringComparer.Ordinal);
                foreach (CygTypeDecl type in _module.Types)
                {
                    if (type is CygStructDecl structDecl)
                    {
                        CollectSupport(structDecl.Fields, support);
                    }
                    else if (type is CygComponentDecl component)
                    {
                        CollectSupport(component.Fields, support);
                    }
                    else if (type is CygUnionDecl union)
                    {
                        foreach (CygUnionVariant variant in union.Variants)
                        {
                            CollectSupport(variant.Fields, support);
                        }
                    }
                }

                if (_module.Input != null)
                {
                    foreach (CygInputField field in _module.Input.Fields)
                    {
                        CollectSupport(field.Type, support);
                    }
                }

                if (_module.Global != null)
                {
                    CollectSupport(_module.Global.Fields, support);
                }

                foreach (CygEventDecl eventDecl in _module.Events)
                {
                    CollectSupport(eventDecl.Fields, support);
                }

                foreach (CygCommandDecl command in _module.Commands)
                {
                    CollectSupport(command.Fields, support);
                }

                foreach (CygSignalDecl signal in _module.Signals)
                {
                    foreach (CygSignalParam parameter in signal.Parameters)
                    {
                        CollectSupport(parameter.Type, support);
                    }
                }

                foreach (string name in support.Keys.OrderBy(k => k, StringComparer.Ordinal))
                {
                    EmitSupportType(indent, name, support[name]);
                    _sb.AppendLine();
                }
            }

            private void CollectSupport(IEnumerable<CygField> fields, Dictionary<string, CygTypeRef> support)
            {
                foreach (CygField field in fields)
                {
                    CollectSupport(field.Type, support);
                }
            }

            private void CollectSupport(CygTypeRef? type, Dictionary<string, CygTypeRef> support)
            {
                if (type == null)
                {
                    return;
                }

                switch (type.Kind)
                {
                    case CygTypeKind.FixedArray:
                    case CygTypeKind.FixedList:
                    case CygTypeKind.FixedDictionary:
                    case CygTypeKind.FixedString:
                        support[CygNames.CsTypeName(type)] = type;
                        break;
                }

                CollectSupport(type.Element, support);
                CollectSupport(type.Key, support);
                CollectSupport(type.Value, support);
            }

            private void EmitSupportType(string indent, string name, CygTypeRef type)
            {
                switch (type.Kind)
                {
                    case CygTypeKind.FixedString:
                        EmitFixedString(indent, name, type.Length);
                        break;
                    case CygTypeKind.FixedArray:
                        EmitFixedArray(indent, name, type);
                        break;
                    case CygTypeKind.FixedList:
                        EmitFixedList(indent, name, type);
                        break;
                    case CygTypeKind.FixedDictionary:
                        EmitFixedDictionary(indent, name, type);
                        break;
                }
            }

            private void EmitFixedString(string indent, string name, int length)
            {
                string body = indent + Indent;
                _sb.Append(indent).AppendLine("[CYGValue]");
                _sb.Append(indent).Append("public partial struct ").Append(name).AppendLine();
                _sb.Append(indent).AppendLine("{");
                _sb.Append(body).Append("public const int Capacity = ").Append(length).AppendLine(";");
                for (int i = 0; i < length; i++)
                {
                    _sb.Append(body).Append("private ushort _c").Append(i).AppendLine(";");
                }
                _sb.AppendLine();
                _sb.Append(body).AppendLine("public void Set(string value)");
