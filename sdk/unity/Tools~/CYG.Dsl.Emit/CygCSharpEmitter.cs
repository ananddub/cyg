            private void EmitFixedDictionary(string indent, string name, CygTypeRef type)
            {
                int capacity = type.Length;
                string key = TypeName(type.Key!);
                string value = TypeName(type.Value!);
                string body = indent + Indent;
                _sb.Append(indent).AppendLine("[CYGValue]");
                _sb.Append(indent).Append("public partial struct ").Append(name).AppendLine();
                _sb.Append(indent).AppendLine("{");
                _sb.Append(body).Append("public const int Capacity = ").Append(capacity).AppendLine(";");
                _sb.Append(body).AppendLine("private int _count;");
                for (int i = 0; i < capacity; i++)
                {
                    _sb.Append(body).Append("private bool _present").Append(i).AppendLine(";");
                    _sb.Append(body).Append("private ").Append(key).Append(" _key").Append(i).AppendLine(";");
                    _sb.Append(body).Append("private ").Append(value).Append(" _value").Append(i).AppendLine(";");
                }
                _sb.AppendLine();
                _sb.Append(body).AppendLine("public int Count");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    get { return _count; }");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();
                _sb.Append(body).Append("public bool TryGetValue(").Append(key).Append(" key, out ").Append(value).AppendLine(" value)");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    for (int i = 0; i < _count; i++)");
                _sb.Append(body).AppendLine("    {");
                _sb.Append(body).AppendLine("        if (GetPresent(i) && KeysEqual(GetKey(i), key))");
                _sb.Append(body).AppendLine("        {");
                _sb.Append(body).AppendLine("            value = GetValue(i);");
                _sb.Append(body).AppendLine("            return true;");
                _sb.Append(body).AppendLine("        }");
                _sb.Append(body).AppendLine("    }");
                _sb.Append(body).Append("    value = default(").Append(value).AppendLine(");");
                _sb.Append(body).AppendLine("    return false;");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();
                _sb.Append(body).Append("public bool ContainsKey(").Append(key).AppendLine(" key)");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).Append("    ").Append(value).AppendLine(" ignored;");
                _sb.Append(body).AppendLine("    return TryGetValue(key, out ignored);");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();
                _sb.Append(body).Append("public void Set(").Append(key).Append(" key, ").Append(value).AppendLine(" value)");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    for (int i = 0; i < _count; i++)");
                _sb.Append(body).AppendLine("    {");
                _sb.Append(body).AppendLine("        if (GetPresent(i) && KeysEqual(GetKey(i), key))");
                _sb.Append(body).AppendLine("        {");
                _sb.Append(body).AppendLine("            SetValue(i, value);");
                _sb.Append(body).AppendLine("            return;");
                _sb.Append(body).AppendLine("        }");
                _sb.Append(body).AppendLine("    }");
                _sb.Append(body).AppendLine("    if (_count >= Capacity)");
                _sb.Append(body).AppendLine("    {");
                _sb.Append(body).AppendLine("        return;");
                _sb.Append(body).AppendLine("    }");
                _sb.Append(body).AppendLine("    SetPresent(_count, true);");
                _sb.Append(body).AppendLine("    SetKey(_count, key);");
                _sb.Append(body).AppendLine("    SetValue(_count, value);");
                _sb.Append(body).AppendLine("    _count++;");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();
                _sb.Append(body).Append("public bool Remove(").Append(key).AppendLine(" key)");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    for (int i = 0; i < _count; i++)");
                _sb.Append(body).AppendLine("    {");
                _sb.Append(body).AppendLine("        if (!GetPresent(i) || !KeysEqual(GetKey(i), key))");
                _sb.Append(body).AppendLine("        {");
                _sb.Append(body).AppendLine("            continue;");
                _sb.Append(body).AppendLine("        }");
                _sb.Append(body).AppendLine("        int last = _count - 1;");
                _sb.Append(body).AppendLine("        if (i != last)");
                _sb.Append(body).AppendLine("        {");
                _sb.Append(body).AppendLine("            SetPresent(i, GetPresent(last));");
                _sb.Append(body).AppendLine("            SetKey(i, GetKey(last));");
                _sb.Append(body).AppendLine("            SetValue(i, GetValue(last));");
                _sb.Append(body).AppendLine("        }");
                _sb.Append(body).AppendLine("        SetPresent(last, false);");
                _sb.Append(body).Append("        SetKey(last, default(").Append(key).AppendLine("));");
                _sb.Append(body).Append("        SetValue(last, default(").Append(value).AppendLine("));");
                _sb.Append(body).AppendLine("        _count--;");
                _sb.Append(body).AppendLine("        return true;");
                _sb.Append(body).AppendLine("    }");
                _sb.Append(body).AppendLine("    return false;");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();
                _sb.Append(body).AppendLine("public void Clear()");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).Append("    this = default(").Append(name).AppendLine(");");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();
                _sb.Append(body).Append("private static bool KeysEqual(").Append(key).Append(" left, ").Append(key).AppendLine(" right)");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).Append("    return System.Collections.Generic.EqualityComparer<").Append(key)
                    .AppendLine(">.Default.Equals(left, right);");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();

                EmitDictionaryAccessors(body, capacity, "bool", "GetPresent", "_present", "return _present", " = value; break;", "false", "SetPresent");
                _sb.AppendLine();
                EmitDictionaryAccessors(body, capacity, key, "GetKey", "_key", "return _key", " = value; break;", "default(" + key + ")", "SetKey");
                _sb.AppendLine();
                EmitDictionaryAccessors(body, capacity, value, "GetValue", "_value", "return _value", " = value; break;", "default(" + value + ")", "SetValue");

                _sb.Append(indent).AppendLine("}");
            }

            private void EmitDictionaryAccessors(
                string body,
                int capacity,
                string type,
                string getter,
                string fieldPrefix,
                string getPrefix,
                string setSuffix,
                string defaultValue,
                string setter)
            {
                _sb.Append(body).Append("private ").Append(type).Append(' ').Append(getter).AppendLine("(int index)");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    switch (index)");
                _sb.Append(body).AppendLine("    {");
                for (int i = 0; i < capacity; i++)
                {
                    _sb.Append(body).Append("        case ").Append(i).Append(": ").Append(getPrefix).Append(i).AppendLine(";");
                }
                _sb.Append(body).Append("        default: return ").Append(defaultValue).AppendLine(";");
                _sb.Append(body).AppendLine("    }");
                _sb.Append(body).AppendLine("}");
                _sb.AppendLine();
                _sb.Append(body).Append("private void ").Append(setter).Append("(int index, ").Append(type).AppendLine(" value)");
                _sb.Append(body).AppendLine("{");
                _sb.Append(body).AppendLine("    switch (index)");
                _sb.Append(body).AppendLine("    {");
                for (int i = 0; i < capacity; i++)
                {
                    _sb.Append(body).Append("        case ").Append(i).Append(": ").Append(fieldPrefix).Append(i)
                        .AppendLine(setSuffix);
                }
                _sb.Append(body).AppendLine("        default: break;");
                _sb.Append(body).AppendLine("    }");
                _sb.Append(body).AppendLine("}");
            }

            private string TypeName(CygTypeRef type)
            {
                string name = CygNames.CsTypeName(type);
                return type.Kind == CygTypeKind.Named ? CygNames.CsIdentifier(name) : name;
            }

            private static string Identifier(string name) => CygNames.CsIdentifier(name);

            private static string NamespaceName(string ns)
                => string.Join(".", ns.Split('.').Select(CygNames.CsIdentifier));

            private static string PrimitiveName(CygPrimitive primitive)
            {
                switch (primitive)
                {
                    case CygPrimitive.Byte: return "byte";
                    case CygPrimitive.SByte: return "sbyte";
                    case CygPrimitive.Int16: return "short";
                    case CygPrimitive.UInt16: return "ushort";
                    case CygPrimitive.Int32: return "int";
                    case CygPrimitive.UInt32: return "uint";
                    case CygPrimitive.Int64: return "long";
                    case CygPrimitive.UInt64: return "ulong";
                    default: return "int";
                }
            }

            private static string ButtonStorage(int count)
            {
                if (count <= 8) return "byte";
                if (count <= 16) return "ushort";
                if (count <= 32) return "uint";
                return "ulong";
            }

            private static string ButtonMask(string storage, int bit)
            {
                switch (storage)
                {
                    case "byte": return "((byte)(1 << " + bit + "))";
                    case "ushort": return "((ushort)(1 << " + bit + "))";
                    case "uint": return "(1U << " + bit + ")";
                    default: return "(1UL << " + bit + ")";
                }
            }
