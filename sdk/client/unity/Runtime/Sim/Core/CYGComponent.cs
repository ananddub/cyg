using System;

namespace CookYourGame.Sim
{
    /// <summary>
    /// Marks a struct for the CYG source generator. The generated partial adds
    /// wire serialization, checksum, and clone helpers without runtime reflection.
    /// </summary>
    [AttributeUsage(AttributeTargets.Struct, AllowMultiple = false, Inherited = false)]
    public sealed class CYGComponentAttribute : Attribute
    {
        public CYGComponentAttribute()
        {
        }

        public CYGComponentAttribute(int id)
        {
            Id = id;
        }

        /// <summary>
        /// Stable wire/type id. Leave 0 to let the generator derive an id from
        /// the fully qualified type name. Set it explicitly before shipping so
        /// renaming a type does not silently change its wire identity.
        /// </summary>
        public int Id { get; set; }
    }

    /// <summary>
    /// Marks a struct as a deterministic value type for the CYG source generator.
    /// The generated partial implements <see cref="ICYGValue"/> without assigning
    /// a component type id, so the struct can be embedded in components.
    /// </summary>
    [AttributeUsage(AttributeTargets.Struct, AllowMultiple = false, Inherited = false)]
    public sealed class CYGValueAttribute : Attribute
    {
    }

    /// <summary>
    /// A deterministic value that can be written to and read from a byte buffer.
    /// Implementations must expose <c>public const int SizeInBytes</c> and must
    /// use the same byte order for writing and checksumming.
    /// </summary>
    public interface ICYGValue
    {
        /// <summary>Wire size in bytes for this value.</summary>
        int WireSize { get; }

        /// <summary>Writes exactly <see cref="WireSize"/> bytes at <paramref name="offset"/>.</summary>
        int WriteTo(byte[] buffer, int offset);

        /// <summary>Reads exactly <see cref="WireSize"/> bytes from <paramref name="offset"/>.</summary>
        void ReadFrom(byte[] buffer, int offset);

        /// <summary>Mixes this value's wire bytes into a CRC32 accumulator.</summary>
        void ComputeChecksum(ref uint crc);
    }

    /// <summary>Top-level deterministic component generated by CYG.CodeGen.</summary>
    public interface ICYGComponent : ICYGValue
    {
        /// <summary>Stable component id used by snapshots and checksums.</summary>
        int ComponentTypeId { get; }

        /// <summary>Field-layout hash. Mismatched builds should fail fast.</summary>
        uint ComponentSchemaHash { get; }
    }
}
