using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis;

namespace CookYourGame.CodeGen
{
    public sealed partial class CYGComponentGenerator
    {
        private static string AccessibilityText(INamedTypeSymbol symbol)
        {
            switch (symbol.DeclaredAccessibility)
            {
                case Accessibility.Public: return "public";
                case Accessibility.Private: return "private";
                case Accessibility.Protected: return "protected";
                case Accessibility.ProtectedAndInternal: return "private protected";
                case Accessibility.ProtectedOrInternal: return "protected internal";
                default: return "internal";
            }
        }

        private static string Emit(
            INamedTypeSymbol symbol,
            List<FieldSpec> fields,
            int id,
            uint schema,
            int size,
            bool isComponent)
        {
            StringBuilder sb = new StringBuilder(2048);
            string indent = string.Empty;
            sb.AppendLine("// <auto-generated by CYG.CodeGen />");
            sb.AppendLine("// Manual edits will be lost when the generator runs again.");

            string ns = symbol.ContainingNamespace == null || symbol.ContainingNamespace.IsGlobalNamespace
                ? string.Empty
                : EscapeNamespace(symbol.ContainingNamespace.ToDisplayString());
            if (!string.IsNullOrEmpty(ns))
            {
                sb.Append("namespace ").Append(ns).AppendLine();
                sb.AppendLine("{");
                indent = "    ";
            }

            string interfaceName = isComponent
                ? "global::CookYourGame.Sim.ICYGComponent"
                : "global::CookYourGame.Sim.ICYGValue";
            sb.Append(indent).Append(AccessibilityText(symbol)).Append(" partial struct ").Append(EscapeIdentifier(symbol.Name))
                .Append(" : ").AppendLine(interfaceName);
            sb.Append(indent).AppendLine("{");

            string body = indent + "    ";
            sb.Append(body).Append("public const int SizeInBytes = ").Append(size).AppendLine(";");
            if (isComponent)
            {
                sb.Append(body).Append("public const int TypeId = ").Append(id).AppendLine(";");
                sb.Append(body).Append("public const uint SchemaHash = 0x").Append(schema.ToString("X8")).AppendLine("u;");
            }
            sb.AppendLine();
            sb.Append(body).AppendLine("public readonly int WireSize => SizeInBytes;");
            if (isComponent)
            {
                sb.Append(body).AppendLine("public readonly int ComponentTypeId => TypeId;");
                sb.Append(body).AppendLine("public readonly uint ComponentSchemaHash => SchemaHash;");
            }
            sb.AppendLine();

            EmitWrite(sb, body, fields);
            sb.AppendLine();
            EmitRead(sb, body, fields);
            sb.AppendLine();
            EmitChecksum(sb, body, fields, isComponent);
            sb.AppendLine();
            sb.Append(body).Append("public readonly void CopyTo(ref ").Append(EscapeIdentifier(symbol.Name)).AppendLine(" destination)");
            sb.Append(body).AppendLine("{");
            sb.Append(body).AppendLine("    destination = this;");
            sb.Append(body).AppendLine("}");

            sb.Append(indent).AppendLine("}");

            if (!string.IsNullOrEmpty(ns))
            {
                sb.AppendLine("}");
            }

            return sb.ToString();
        }
    }
}
